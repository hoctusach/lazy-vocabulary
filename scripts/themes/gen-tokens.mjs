import fs from 'node:fs';
import { THEMES } from './palettes.mjs';

const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const lum = (h) => { const [r, g, b] = rgb(h).map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const cr = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };
function hsl(h) {
  let [r, g, b] = rgb(h).map((v) => v / 255);
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b); let H = 0, S = 0; const L = (mx + mn) / 2;
  if (mx !== mn) { const d = mx - mn; S = L > 0.5 ? d / (2 - mx - mn) : d / (mx + mn); H = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; H *= 60; }
  return `${Math.round(H)} ${Math.round(S * 100)}% ${Math.round(L * 100)}%`;
}
const CHECKS = [['ink', 'bg', 4.5], ['ink', 'card', 4.5], ['sub', 'bg', 4.5], ['sub', 'card', 4.5], ['accent', 'bg', 4.5], ['accent', 'card', 4.5],
  ['btnInk', 'btn', 4.5], ['okInk', 'ok', 4.5], ['meaning', 'card', 4.5], ['example', 'card', 4.5], ['translation', 'card', 4.5],
  ['error', 'card', 4.5], ['warning', 'card', 4.5], ['field', 'card', 3], ['ink', 'cardHi', 4.5], ['sub', 'cardHi', 4.5]];
let fail = 0; const out = ['/* GENERATED by scripts/themes/gen-tokens.mjs from scripts/themes/palettes.mjs. Do not edit by hand. */'];
for (const [id, modes] of Object.entries(THEMES)) for (const [mode, p] of Object.entries(modes)) {
  for (const [a, b, min] of CHECKS) { const r = cr(p[a], p[b]); if (r < min) { fail++; console.log(`FAIL ${id}/${mode} ${a} on ${b}: ${r.toFixed(2)} < ${min}`); } }
  const sel = mode === 'dark' ? `html.dark body.theme-${id}` : `body.theme-${id}`;
  out.push(`${sel} {
  --background: ${hsl(p.bg)};
  --foreground: ${hsl(p.ink)};
  --card: ${hsl(p.card)};
  --card-foreground: ${hsl(p.ink)};
  --popover: ${hsl(p.card)};
  --popover-foreground: ${hsl(p.ink)};
  --primary: ${hsl(p.btn)};
  --primary-foreground: ${hsl(p.btnInk)};
  --secondary: ${hsl(p.cardHi)};
  --secondary-foreground: ${hsl(p.ink)};
  --muted: ${hsl(p.cardHi)};
  --muted-foreground: ${hsl(p.sub)};
  --accent: ${hsl(p.cardHi)};
  --accent-foreground: ${hsl(p.ink)};
  --destructive: ${hsl(mode === 'dark' ? p.error : p.error)};
  --destructive-foreground: ${mode === 'dark' ? hsl(p.bg) : '0 0% 100%'};
  --border: ${hsl(p.line)};
  --input: ${hsl(p.field)};
  --ring: ${hsl(p.accent)};

  --lv-bg: ${p.bg};
  --lv-surface: ${p.card};
  --lv-body-bg: ${p.bg};
  --lv-card-bg: ${p.card};
  --lv-card-highlight: ${p.cardHi};
  --lv-text-primary: ${p.ink};
  --lv-text-secondary: ${p.sub};
  --lv-heading: ${p.accent};
  --lv-subheading: ${p.sub};
  --lv-accent: ${p.accent};
  --lv-accent-soft: ${p.hl}40;
  --lv-border-color: ${p.line};
  --lv-hl: ${p.hl};
  --lv-deco: ${p.deco};
  --lv-ink: ${p.ink};
${p.tones.map((t, i) => `  --lv-card-tone-${i + 1}: ${t};`).join('\n')}
  --lv-word-title: ${p.ink};
  --lv-meaning: ${p.meaning};
  --lv-example: ${p.example};
  --lv-translation: ${p.translation};
  --lv-info: ${p.accent};
  --lv-error: ${p.error};
  --lv-success: ${p.ok};
  --lv-on-success: ${p.okInk};
  --lv-warning: ${p.warning};
  --lv-focus-ring: ${p.accent};
  --lv-overlay: ${p.overlay};
  --lv-button-primary-bg: ${p.btn};
  --lv-button-primary-text: ${p.btnInk};
  --lv-button-secondary-bg: ${p.card};
  --lv-button-secondary-text: ${p.ink};
  --lv-field-bg: ${p.card};
  --lv-field-border: ${p.field};
  --lv-field-text: ${p.ink};
  --lv-helper-text: ${p.sub};
}
`);
}
fs.writeFileSync(new URL('../../src/styles/theme-tokens.css', import.meta.url), out.join('\n'));
console.log(fail ? `${fail} contrast failures` : 'all contrast checks pass');
process.exit(fail ? 1 : 0);
