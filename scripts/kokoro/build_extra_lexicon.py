#!/usr/bin/env python3
"""Build android/app/src/main/assets/kokoro/cmudict-extra-us.txt.

Supplementary US-English lexicon for the on-device Kokoro voices. The primary
lexicon (misaki-style, lexicon-us-en.txt, Apache-2.0) is downloaded with the
model; it lacks many inflected forms ("events", "arrived"). This adds every
CMU Pronouncing Dictionary headword (BSD-2-Clause, pinned commit) that the
primary lexicon lacks, converted from ARPAbet to Kokoro/misaki phoneme symbols.

No espeak-ng (GPL) is used anywhere in this pipeline.

Usage: python3 scripts/kokoro/build_extra_lexicon.py /path/to/lexicon-us-en.txt
"""
import re, sys, urllib.request, hashlib
from pathlib import Path

CMU_COMMIT = "74790861f652b15e4ac49015a90074ad62a27690"
CMU_URL = f"https://raw.githubusercontent.com/cmusphinx/cmudict/{CMU_COMMIT}/cmudict.dict"
OUT = Path(__file__).resolve().parents[2] / "android/app/src/main/assets/kokoro/cmudict-extra-us.txt"

M = {'AA':'ɑ','AE':'æ','AO':'ɔ','AW':'W','AY':'I','EH':'ɛ','EY':'A','IH':'ɪ','IY':'i','OW':'O','OY':'Y',
     'UH':'ʊ','UW':'u','B':'b','CH':'ʧ','D':'d','DH':'ð','F':'f','G':'ɡ','HH':'h','JH':'ʤ','K':'k','L':'l',
     'M':'m','N':'n','NG':'ŋ','P':'p','R':'ɹ','S':'s','SH':'ʃ','T':'t','TH':'θ','V':'v','W':'w','Y':'j',
     'Z':'z','ZH':'ʒ'}

def conv(ph):
    out = []
    for p in ph:
        b, s = re.match(r'([A-Z]+)([012]?)$', p).groups()
        st = {'1': 'ˈ', '2': 'ˌ'}.get(s, '')
        if b == 'AH': out.append(st + ('ə' if s in ('0', '') else 'ʌ'))
        elif b == 'ER': out.append(st + ('ɜɹ' if s in ('1', '2') else 'əɹ'))
        else: out.append(st + M[b])
    return ''.join(out)

def main():
    lex_path = Path(sys.argv[1])
    known = {l.split(' ', 1)[0] for l in lex_path.open(encoding='utf-8')}
    raw = urllib.request.urlopen(CMU_URL).read().decode('utf-8')
    extra = {}
    for line in raw.splitlines():
        line = line.split('#')[0].strip()
        if not line: continue
        w, *ph = line.split()
        if '(' in w or w in known or w in extra or not re.fullmatch(r"[a-z']+", w): continue
        extra[w] = conv(ph)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    header = (f"# Derived from the CMU Pronouncing Dictionary (cmusphinx/cmudict@{CMU_COMMIT}),\n"
              "# Copyright (C) 1993-2015 Carnegie Mellon University. BSD-2-Clause; see THIRD_PARTY_NOTICES.md.\n"
              "# Format: word<space>phonemes (Kokoro/misaki US symbols). Generated by scripts/kokoro/build_extra_lexicon.py\n")
    OUT.write_text(header + ''.join(f"{w} {p}\n" for w, p in sorted(extra.items())), encoding='utf-8')
    print(f"wrote {OUT} ({len(extra)} words, sha256 {hashlib.sha256(OUT.read_bytes()).hexdigest()})")

if __name__ == '__main__':
    main()
